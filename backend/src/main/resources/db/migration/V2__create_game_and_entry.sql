CREATE TABLE game (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(255) NOT NULL,
    series              VARCHAR(255),
    rating              SMALLINT CHECK (rating BETWEEN 1 AND 10),
    cover_image_url     TEXT,
    igdb_id             BIGINT UNIQUE,
    steam_app_id        BIGINT UNIQUE,
    metadata_fetched_at TIMESTAMPTZ
);

CREATE TABLE entry (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id          BIGINT NOT NULL REFERENCES game (id) ON DELETE CASCADE,
    platform_id      BIGINT NOT NULL REFERENCES platform (id),
    playtime_minutes INTEGER NOT NULL DEFAULT 0 CHECK (playtime_minutes >= 0),
    status           VARCHAR(20) NOT NULL
        CHECK (status IN ('NOT_STARTED', 'PLAYING', 'FINISHED', 'COMPLETED', 'DROPPED')),
    playtime_source  VARCHAR(10) NOT NULL DEFAULT 'MANUAL'
        CHECK (playtime_source IN ('MANUAL', 'STEAM')),
    -- A game can have at most one entry per platform.
    CONSTRAINT entry_game_platform_unique UNIQUE (game_id, platform_id)
);

-- The unique constraint already indexes game_id. This one covers lookups by platform.
CREATE INDEX entry_platform_id_idx ON entry (platform_id);
